export const getRoleLabel = (role, lang = 'tr') => {
  const t = TRANSLATIONS[lang] || TRANSLATIONS.tr
  switch (role) {
    case 'admin': return t.roleAdmin
    case 'manager': return t.roleManager
    case 'accountant': return t.roleAccountant
    case 'financial_advisor': return t.roleAdvisor
    case 'chef': return t.roleChef
    case 'warehouse': return t.roleWarehouse
    default: return role
  }
}

