export const getLocalizedNotification = (notif, lang = 'tr') => {
  if (!notif) return { title: '', message: '' }
  const mapping = NOTIF_MAP[notif.type]
  if (mapping) {
    const title = mapping.title[lang] || notif.title
    // Eğer mesaj sistem tarafından özel parametreyle üretildiyse (örn güvenlik uyarısı ve kullanıcı adı içeriyorsa)
    const message = (lang === 'tr' || !mapping.message[lang]) ? notif.message : mapping.message[lang]
    return { title, message }
  }
  return { title: notif.title, message: notif.message }
}


